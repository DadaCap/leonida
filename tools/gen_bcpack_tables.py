"""Writes runtime/src/bcpack_tables.h, the runtime's copy of tools/bcpack_tables.py and bcpack_tables_bptc.py.

Standard library only. No game data: the tables are the codec's own constants, as the Python modules hold them.

    python -I tools/gen_bcpack_tables.py            # rewrite the header
    python -I tools/gen_bcpack_tables.py --check    # exit 1 when it is stale
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bcpack  # noqa: E402
import bcpack_tables as tables  # noqa: E402
import bcpack_tables_bptc as bptc  # noqa: E402

HEADER = os.path.join(os.path.dirname(HERE), "runtime", "src", "bcpack_tables.h")


def _rows(values, per_line=24):
    values = list(values)
    return ",\n".join("    " + ", ".join(str(v) for v in values[i:i + per_line])
                      for i in range(0, len(values), per_line))


def _array(kind, name, values, shape=""):
    return f"inline constexpr {kind} {name}[{shape or len(values)}] = {{\n{_rows(values)}}};\n"


def _table(kind, name, rows):
    body = ",\n".join("    {" + ", ".join(str(v) for v in row) + "}" for row in rows)
    return f"inline constexpr {kind} {name}[{len(rows)}][{len(rows[0])}] = {{\n{body}}};\n"


def _history(confirmed, provisional, values):
    """256 entries; a first value of -1 marks one nobody has measured."""
    return [tuple(confirmed.get(k, provisional.get(k, (-1,) + (0,) * (values - 1)))) for k in range(256)]


def generate():
    side = bcpack.MAX_WIDTH + 1
    probability = []
    for w in range(side):
        for q in range(16):
            freq = tables.PROB_TABLES.get((w, q))
            row = list(freq) if freq is not None and len(freq) == w + 1 else [-1]
            probability.append(tuple(row + [0] * (side - len(row))))
    bc7 = bptc.load_bc7(None)
    plans = [((), 0)] + [bcpack._bc6h_plan(bcpack._BC6H_CODE[mode]) for mode in range(1, 15)]
    parts = [
        "#pragma once\n\n"
        "// Generated by tools/gen_bcpack_tables.py from tools/bcpack_tables.py and tools/bcpack_tables_bptc.py; run it\n"
        "// again instead of editing this file (tests/test_gen_bcpack_tables.py checks that it is current).\n\n"
        "#include <cstdint>\n\n"
        "namespace leonida::bcpack::tables {\n\n"
        f"inline constexpr unsigned kMaxWidth = {bcpack.MAX_WIDTH};\n"
        "// [width * 16 + q]: the frequency of each symbol bit length; -1 first: no table.\n",
        _table("std::int32_t", "kProbability", probability),
        _array("std::uint8_t", "kBc1Quadrant", tables.BC1_QUADRANT),
        _array("std::uint8_t", "kBc3ColourQuadrant", tables.BC3_COLOUR_QUADRANT),
        _table("std::uint8_t", "kBc3AlphaPair", tables.BC3_ALPHA_PAIR),
        _table("std::uint8_t", "kBc4Pair", tables.BC4_PAIR),
        _table("std::uint8_t", "kBc5Pair", tables.BC5_PAIR),
        "// The built-in histories: confirmed entries, else provisional ones; -1 first: not known.\n",
    ]
    for name, codec, values in (("kBc1History", "BC1", 6), ("kBc3History", "BC3", 8),
                                ("kBc4History", "BC4", 2), ("kBc5History", "BC5", 4)):
        parts.append(_table("std::int16_t", name, _history(
            getattr(tables, f"{codec}_HISTORY_CONFIRMED"), getattr(tables, f"{codec}_HISTORY_PROVISIONAL"), values)))
    parts += [
        "// BPTC partitions and anchors (public D3D11 / Khronos tables): one bit, or two, a pixel.\n",
        _array("std::uint16_t", "kPartition2", bptc.BC7_PART2_PACKED),
        _array("std::uint32_t", "kPartition3", [f"{v}u" for v in bptc.BC7_PART3_PACKED]),
        _array("std::uint8_t", "kAnchor2", bptc.BC7_ANCHOR2),
        _array("std::uint8_t", "kAnchor3a", bptc.BC7_ANCHOR3A),
        _array("std::uint8_t", "kAnchor3b", bptc.BC7_ANCHOR3B),
        "// BC7 lane 15: signature -> rank -> mode, partition, rotation, index selection.\n",
        _array("std::int16_t", "kBc7Rank", bc7["rank_of"]),
        _table("std::uint8_t", "kBc7Config", bptc.BC7_CONFIG),
        "// BC6H: where each header bit of a mode comes from (channel -1: the partition) and goes.\n"
        "struct Bc6hBit {\n    std::int8_t channel, slot;\n    std::uint8_t bit, position;\n};\n"
        f"struct Bc6hPlan {{\n    std::uint8_t count, header_bits;\n    Bc6hBit bit[{max(len(p) for p, _ in plans)}];\n}};\n"
        f"inline constexpr Bc6hPlan kBc6hPlan[{len(plans)}] = {{\n"
        + ",\n".join("    {%d, %d, {%s}}" % (len(plan), header, ", ".join("{%d, %d, %d, %d}" % bit for bit in plan))
                     for plan, header in plans)
        + "};\n",
        "\n}  // namespace leonida::bcpack::tables\n",
    ]
    return "".join(parts)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the header is not what this would write")
    args = parser.parse_args(argv)
    text = generate()
    if args.check:
        try:
            with open(HEADER, encoding="utf-8", newline="") as f:
                current = f.read().replace("\r\n", "\n")
        except OSError:
            current = None
        if current != text:
            print("runtime/src/bcpack_tables.h is stale: run python -I tools/gen_bcpack_tables.py")
            return 1
        return 0
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
